#!/usr/bin/env python3
"""Emit SOURCES.md: a provenance + integrity table for everything in sources/.

Reads sources.manifest.json, hashes each local file, and writes a markdown table
so a later reader can (a) see exactly where each document came from, (b) confirm
the licence basis for keeping it in this folder, and (c) verify their copy has not
been swapped or truncated.

Usage:
    python write_provenance.py            # writes sources/SOURCES.md
    python write_provenance.py --check    # verify hashes against SOURCES.md, exit 1 on drift
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
SOURCES = ROOT / "sources"
OUT = SOURCES / "SOURCES.md"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def human(n: int) -> str:
    value = float(n)
    for unit in ("B", "KB", "MB", "GB"):
        if value < 1024:
            return f"{value:.1f}{unit}"
        value /= 1024.0
    return f"{value:.1f}TB"


def build() -> str:
    entries = json.loads((HERE / "sources.manifest.json").read_text(encoding="utf-8"))["sources"]
    lines = [
        "# Source provenance and integrity",
        "",
        "Every document in this folder is either a **US Government work** (public domain under",
        "17 U.S.C. §105, which excludes US Government works from copyright protection) or an",
        "**openly licensed** standard. Nothing here is a copyrighted commercial textbook, and no",
        "source was obtained from a shadow library. Re-verify the licence note before redistributing",
        "any file outside this repository.",
        "",
        "Generated by [`tools/write_provenance.py`](../tools/write_provenance.py).",
        f"Last generated: {date.today().isoformat()}",
        "",
        "| File | Title | Publisher | Year | Size | SHA-256 (first 16) | Licence basis |",
        "|---|---|---|---|---|---|---|",
    ]
    for e in entries:
        path = SOURCES / e["file"]
        if path.exists():
            size, digest = human(path.stat().st_size), sha256(path)[:16]
        else:
            size, digest = "MISSING", "-"
        lines.append(
            f"| `{e['file']}` | {e['title']} | {e['publisher']} | {e['year']} | "
            f"{size} | `{digest}` | {e['license']} |"
        )

    lines += ["", "## Why each source is in the set", ""]
    for e in entries:
        lines += [
            f"### {e['title']}",
            "",
            f"- **Local file**: `{e['file']}`",
            f"- **Canonical page**: <{e['page']}>",
            f"- **Retrieved from**: <{e['url']}>",
            f"- **Licence**: {e['license']}",
            f"- **Role in this set**: {e['why']}",
            "",
        ]

    lines += [
        "## Retrieval notes (host-specific, kept because they cost real time to discover)",
        "",
        "This machine's TLS setup makes the obvious approach fail:",
        "",
        "- `git` and `curl` default to the **schannel** TLS backend, which fails here with",
        "  `schannel: AcquireCredentialsHandle failed: SEC_E_NO_CREDENTIALS (0x8009030e)`.",
        "  Cloning or downloading without forcing another backend does not work.",
        "- The extraction host reached the internet through an **HTTP proxy**. Python's `urllib`",
        "  picks the proxy up from `HTTPS_PROXY` automatically, provided it is set.",
        "- Several `.gov` hosts (`rosap.ntl.bts.gov`, `www.nrc.gov`) return **403** to a bare",
        "  `Mozilla/5.0` User-Agent. A complete desktop-browser header set is required.",
        "",
        "`tools/fetch_sources.py` encodes all three fixes and is the supported way to re-fetch:",
        "",
        "```bash",
        "python tools/fetch_sources.py          # fetch whatever is missing",
        "python tools/fetch_sources.py --list   # show manifest and on-disk status",
        "python tools/write_provenance.py --check   # verify local hashes have not drifted",
        "```",
        "",
    ]
    return "\n".join(lines)


def check() -> int:
    if not OUT.exists():
        print(f"{OUT} does not exist; run without --check first", file=sys.stderr)
        return 2
    recorded = dict(
        re.findall(r"\| `([^`]+)` \|.*?\| `([0-9a-f]{16})` \|", OUT.read_text(encoding="utf-8"))
    )
    entries = json.loads((HERE / "sources.manifest.json").read_text(encoding="utf-8"))["sources"]
    bad = 0
    for e in entries:
        want = recorded.get(e["file"])
        path = SOURCES / e["file"]
        if want is None:
            print(f"[skip] {e['file']}: no recorded hash")
            continue
        if not path.exists():
            print(f"[FAIL] {e['file']}: missing on disk")
            bad += 1
            continue
        got = sha256(path)[:16]
        if got == want:
            print(f"[ ok ] {e['file']}")
        else:
            print(f"[FAIL] {e['file']}: recorded {want}, actual {got}")
            bad += 1
    print(f"\n{bad} drift(s)")
    return 1 if bad else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify hashes instead of writing")
    args = ap.parse_args()
    if args.check:
        return check()
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
