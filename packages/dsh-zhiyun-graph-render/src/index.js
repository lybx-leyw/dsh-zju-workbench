/**
 * 笔记链接图的**渲染层**（宿主半边）。
 *
 * # 为什么是独立包，而不是塞进「笔记」页
 *
 * 这个包是**整包移植**的产物 —— 从生态雷达候选 `packages/radar/dsh-radar-note-graph`
 * 搬过来。移植的含义是「整个东西搬到一个正式位置」，不是「把能用的部分摘出来
 * 塞进别的包」。后者叫**能力提取**，两者的处置不同：
 *
 * | 模式 | 落点 | 骨架 |
 * | --- | --- | --- |
 * | **移植** | 新建正式包，整包搬迁 | 删除（能力已全部搬走） |
 * | **提取** | 写进**已有的**目标包 | 保留，标 🅿️（可能还有剩余能力） |
 *
 * 本项目里两种模式都发生过，但**不能混用**：一旦把移植拆散了塞进页面包，
 * 页面就会背上一份渲染依赖（cytoscape 及其布局扩展），
 * 而这份依赖本来只属于「画图」这件事。
 *
 * # 职责边界
 *
 * - **不做数据**：`{nodes, edges}` 由 `dsh-zhiyun-core-vault` 算好并下发，
 *   本包不重算入度出度（重算就会出现两套口径）。
 * - **不做存储**：布局偏好之类的持久化不属于这里。
 * - **不新增页面**：只有组件与纯函数，由「笔记」页 import 使用。
 */

