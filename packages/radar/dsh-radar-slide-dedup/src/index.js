/**
 * TODO-0（阻塞）· 落点与调用顺序
 *
 * `generateLecture()` 的第一行是 `if (record.tree?.kind !== 'title') throw ...`，
 * 而 `record.tree` 是**上游已经建好的树**。也就是说：若在建树时就把重复页算进去了，
 * 这里再剔 `pages` 已经来不及 —— 树已经错了。
 *
 * → 落点必须上移到**建树之前**：`dsh-zhiyun-core-parser` 产出 `record.pages` 与
 *   `record.tree` 之间。需评审确认改哪一侧：
 *     (a) 在 parser 侧用去重后的 `pages` 建树（推荐：树从源头就是对的）；
 *     (b) 在 lecture 侧「建树 → 发现重复页 → 重建树」（多一次纯计算，但不动 parser）。
 *   **不接受**只剔 `pages` 不重建树 —— 那会让 `slideEvidence` 的页号全部指向不存在的页。
 */

/**
 * TODO-1（阻塞）· 页号**不重编**
 *
 * `buildLectureTree` 的 `fromPage` / `toPage`、`organize.js` 的
 * `Math.abs(n - p.page) <= 1`（取相邻页证据）都以**原课件页号**为坐标。
 * 去重后若把页号压成 1..n，所有页码引用静默错位，且**不会报错**。
 *
 * → 输出必须是「原 `pages` 数组的子序列」，被丢掉的页只从序列里消失，**其余页的 `page` 一字不动**。
 *   验收：`output.every(p => input.some(q => q.page === p.page && q === p))`。
 */

/**
 * TODO-2（阻塞）· 判定优先级：文本 → 像素 → 页号
 *
 * 三级，**依次降级**，任一级判同即丢弃该页并把它的 `page` 记入「它重复了谁」的映射：
 *
 *   1. **文本近重**（主判据）：`pageText` 归一化（去空白 / 全半角 / 去掉「第 N 页」页脚）后相等。
 *      回看的帧文本必然一致，这是最高信噪比的一级。
 *   2. **像素近重**（兜底）：`pageText` 为空或极短（< 8 字，典型是纯公式/示意图页）时才走。
 *      32×32 缩略图、逐通道差 < 30 记同像素、同像素率 ≥ 0.9 —— 这三个数是上游的工程值，
 *      **须用真机样本重标**，不可照抄后当定论。
 *   3. **页号连续性**（约束，不是判据）：`page` 倒退是「回看」的强信号，但它**不能单独判定重复**
 *      （老师也可能真的翻回一页讲不同的内容）。
 *
 * → 评审要拍板的点是：**第 1 级的「相等」是否允许近似**（例如只差一个标点）。
 *   建议 v1 用**严格相等 + 空白归一化**，不做编辑距离 —— 宁可漏杀，不可错杀。
 */

/**
 * TODO-3 · 丢弃粒度：**整页**，不按行
 *
 * 一页 PPT 若与前面某页的**画面**相同但**字幕**不同（老师回看时补充讲了新内容），
 * 那么这页的字幕是**新信息**，只是画面冗余。
 *
 * → 需决定：字幕是否并入被重复的那一页（`sentences` 追加），而不是随页面一起丢掉。
 *   若不做这一步，回看时的补充讲解会**整段消失** —— 这比多一个知识点更伤。
 *   建议：保留页删除、句子迁移，并在 `warnings` 里记一条「第 N 页与第 M 页同画面，字幕已并入」。
 */

/**
 * TODO-4 · 与「模板/页眉」判据的**先后**关系
 *
 * `tree.js` 的 `kTreeHeaderMinPages = 3` 与 `detectSlideTemplate()` 依赖「同一行在多少页上出现」。
 * 去重会**减少分母**（页数变少），从而**抬高**每一行的出现占比。
 *
 * → 必须先定顺序：若先去重再判页眉，一份 12 页的课件去掉 3 页重复只剩 9 页，
 *   原先占比 25% 的「跨 3 页标题」会变成 33%，**逼近 40% 的页眉阈值**，存在真标题被误判成页眉的风险。
 *   建议：**先在原始 pages 上判模板与页眉，再去重**；去重只影响「树的内容」，不影响「模板判定」。
 */

/**
 * TODO-5 · 上限：最多丢多少
 *
 * 一份 40 页的课件若被判成「丢 30 页」，几乎一定是判据失效（例如整节课只展示了一张静态图）。
 *
 * → 需要一条硬护栏：**丢弃比例超过 N% 时整体放弃去重并写 warning**。
 *   建议 N = 40，并在 UI 上明示「本讲检测到大量重复帧，未做去重」。
 *   **不接受**静默丢弃 —— 用户会以为老师只讲了几页。
 */

